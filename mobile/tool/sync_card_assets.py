#!/usr/bin/env python3
"""Copy the web's card artwork + catalog into the Flutter app.

Source of truth is the web build (client/scripts/build-card-catalog.mjs):
  client/public/cards/**        -> mobile/assets/cards/**
  client/lib/cardCatalog.json   -> mobile/assets/card_catalog.json
and rewrites the asset folder list in pubspec.yaml (Flutter needs every
sub-folder listed). Run from anywhere:  python3 mobile/tool/sync_card_assets.py
"""
import pathlib, re, shutil

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC_CARDS = ROOT / 'client' / 'public' / 'cards'
SRC_JSON = ROOT / 'client' / 'lib' / 'cardCatalog.json'
MOBILE = ROOT / 'mobile'
DST_CARDS = MOBILE / 'assets' / 'cards'
PUBSPEC = MOBILE / 'pubspec.yaml'
BEGIN, END = '    # card-art:begin (generated by tool/sync_card_assets.py)', '    # card-art:end'

shutil.rmtree(DST_CARDS, ignore_errors=True)
shutil.copytree(SRC_CARDS, DST_CARDS)
shutil.copy2(SRC_JSON, MOBILE / 'assets' / 'card_catalog.json')

dirs = sorted(p.name for p in DST_CARDS.iterdir() if p.is_dir())
block = '\n'.join([BEGIN, '    - assets/card_catalog.json'] + [f'    - assets/cards/{d}/' for d in dirs] + [END])

text = PUBSPEC.read_text()
if BEGIN in text:
    text = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), block, text, flags=re.S)
else:
    text = text.replace('    - assets/nav/\n', '    - assets/nav/\n' + block + '\n', 1)
PUBSPEC.write_text(text)

files = list(DST_CARDS.rglob('*.webp'))
size = sum(f.stat().st_size for f in files)
print(f'{len(files)} files, {size / 1048576:.1f}MB, {len(dirs)} bank folders')
